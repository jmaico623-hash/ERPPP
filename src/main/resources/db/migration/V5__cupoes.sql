-- NanoBanana ERP - V5
-- Persistência de cupões de desconto

CREATE TABLE IF NOT EXISTS cupoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    desconto_percent NUMERIC(5,2) NOT NULL,
    tenant_id UUID,
    ativo BOOLEAN NOT NULL DEFAULT true,
    criado_em TIMESTAMP NOT NULL,
    CONSTRAINT fk_cupom_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id),
    CONSTRAINT chk_cupom_desconto_percent CHECK (desconto_percent > 0 AND desconto_percent <= 100)
);

CREATE INDEX IF NOT EXISTS idx_cupom_tenant ON cupoes(tenant_id);
CREATE INDEX IF NOT EXISTS idx_cupom_codigo ON cupoes(codigo);
