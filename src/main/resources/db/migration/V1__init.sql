-- NanoBanana ERP - Schema inicial (Flyway V1)
-- Compatível com entidades JPA atuais

CREATE TABLE IF NOT EXISTS tenants (
    id UUID PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    nui VARCHAR(100),
    email VARCHAR(255) UNIQUE NOT NULL,
    telefone VARCHAR(50),
    endereco TEXT,
    plano VARCHAR(50) NOT NULL DEFAULT 'teste',
    data_inicio DATE NOT NULL,
    data_expiracao DATE,
    ativo BOOLEAN NOT NULL DEFAULT true,
    alertas_ativos BOOLEAN NOT NULL DEFAULT true,
    auditoria_stock BOOLEAN NOT NULL DEFAULT true,
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP
);

CREATE TABLE IF NOT EXISTS usuarios (
    id UUID PRIMARY KEY,
    tenant_id UUID NOT NULL,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    telefone VARCHAR(50),
    role VARCHAR(50) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT true,
    ultimo_login TIMESTAMP,
    tentativas_falhas INTEGER NOT NULL DEFAULT 0,
    bloqueado BOOLEAN NOT NULL DEFAULT false,
    criado_em TIMESTAMP NOT NULL,
    criado_por UUID,
    CONSTRAINT fk_usuario_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id)
);

CREATE TABLE IF NOT EXISTS admins (
    id SERIAL PRIMARY KEY,
    email VARCHAR(255) UNIQUE NOT NULL,
    senha VARCHAR(255) NOT NULL,
    nome VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS produtos (
    id UUID PRIMARY KEY,
    tenant_id UUID NOT NULL,
    codigo_barras VARCHAR(50),
    nome VARCHAR(255) NOT NULL,
    categoria VARCHAR(100),
    preco_custo NUMERIC(10,2),
    preco_venda NUMERIC(10,2) NOT NULL,
    stock_atual INTEGER NOT NULL DEFAULT 0,
    stock_minimo INTEGER NOT NULL DEFAULT 5,
    stock_maximo INTEGER,
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP,
    CONSTRAINT fk_produto_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id)
);

CREATE TABLE IF NOT EXISTS vendas (
    id UUID PRIMARY KEY,
    tenant_id UUID NOT NULL,
    vendedor_id UUID NOT NULL,
    cliente_id UUID,
    subtotal NUMERIC(10,2),
    desconto NUMERIC(10,2) DEFAULT 0,
    total NUMERIC(10,2) NOT NULL,
    metodo_pagamento VARCHAR(50),
    status VARCHAR(50) NOT NULL DEFAULT 'CONCLUIDA',
    nome_cliente_fiado VARCHAR(255),
    telefone_cliente_fiado VARCHAR(50),
    valor_pago NUMERIC(10,2),
    troco NUMERIC(10,2),
    data_hora TIMESTAMP NOT NULL,
    cancelada_por UUID,
    motivo_cancelamento TEXT,
    hash VARCHAR(255),
    observacao TEXT,
    CONSTRAINT fk_venda_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id),
    CONSTRAINT fk_venda_vendedor FOREIGN KEY (vendedor_id) REFERENCES usuarios(id)
);

CREATE TABLE IF NOT EXISTS venda_itens (
    id UUID PRIMARY KEY,
    venda_id UUID NOT NULL,
    produto_id UUID NOT NULL,
    nome_produto VARCHAR(255) NOT NULL,
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(10,2) NOT NULL,
    subtotal NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_venda_item_venda FOREIGN KEY (venda_id) REFERENCES vendas(id),
    CONSTRAINT fk_venda_item_produto FOREIGN KEY (produto_id) REFERENCES produtos(id)
);

CREATE TABLE IF NOT EXISTS fiados (
    id UUID PRIMARY KEY,
    tenant_id UUID NOT NULL,
    venda_id UUID,
    nome_cliente VARCHAR(255) NOT NULL,
    telefone_cliente VARCHAR(50),
    valor NUMERIC(10,2) NOT NULL,
    pago BOOLEAN NOT NULL DEFAULT false,
    data_pagamento TIMESTAMP,
    data_criacao TIMESTAMP NOT NULL,
    CONSTRAINT fk_fiado_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id),
    CONSTRAINT fk_fiado_venda FOREIGN KEY (venda_id) REFERENCES vendas(id)
);

CREATE TABLE IF NOT EXISTS pagamentos (
    id UUID PRIMARY KEY,
    tenant_id UUID NOT NULL,
    valor NUMERIC(10,2) NOT NULL,
    data DATE NOT NULL,
    metodo VARCHAR(50) NOT NULL,
    referencia VARCHAR(255),
    confirmado BOOLEAN NOT NULL DEFAULT false,
    CONSTRAINT fk_pagamento_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id)
);

CREATE TABLE IF NOT EXISTS alertas_sistema (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id UUID NOT NULL,
    tipo VARCHAR(100) NOT NULL,
    descricao TEXT NOT NULL,
    severidade VARCHAR(20) NOT NULL,
    usuario_relacionado UUID,
    registro_id UUID,
    lido BOOLEAN NOT NULL DEFAULT false,
    resolvido BOOLEAN NOT NULL DEFAULT false,
    resolvido_em TIMESTAMP,
    resolvido_por UUID,
    criado_em TIMESTAMP NOT NULL,
    CONSTRAINT fk_alerta_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id)
);

CREATE TABLE IF NOT EXISTS auditoria_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id UUID NOT NULL,
    acao VARCHAR(100) NOT NULL,
    tabela_afetada VARCHAR(100),
    registro_id UUID,
    dados_antigos TEXT,
    dados_novos TEXT,
    ip_address VARCHAR(50),
    user_agent TEXT,
    data_hora TIMESTAMP NOT NULL,
    CONSTRAINT fk_auditoria_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id)
);

CREATE TABLE IF NOT EXISTS entradas_stock (
    id UUID PRIMARY KEY,
    tenant_id UUID NOT NULL,
    produto_id UUID NOT NULL,
    quantidade INTEGER NOT NULL,
    dono_id UUID NOT NULL,
    fornecedor VARCHAR(255),
    nota_fiscal VARCHAR(100),
    preco_custo NUMERIC(10,2),
    motivo TEXT,
    data_entrada TIMESTAMP NOT NULL,
    hash VARCHAR(255),
    CONSTRAINT fk_entrada_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id),
    CONSTRAINT fk_entrada_produto FOREIGN KEY (produto_id) REFERENCES produtos(id),
    CONSTRAINT fk_entrada_dono FOREIGN KEY (dono_id) REFERENCES usuarios(id)
);

CREATE TABLE IF NOT EXISTS baixas_stock (
    id UUID PRIMARY KEY,
    tenant_id UUID NOT NULL,
    produto_id UUID NOT NULL,
    quantidade INTEGER NOT NULL,
    dono_id UUID NOT NULL,
    tipo_baixa VARCHAR(50) NOT NULL,
    motivo TEXT NOT NULL,
    data_baixa TIMESTAMP NOT NULL,
    hash VARCHAR(255),
    CONSTRAINT fk_baixa_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id),
    CONSTRAINT fk_baixa_produto FOREIGN KEY (produto_id) REFERENCES produtos(id),
    CONSTRAINT fk_baixa_dono FOREIGN KEY (dono_id) REFERENCES usuarios(id)
);

