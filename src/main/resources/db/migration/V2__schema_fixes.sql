-- NanoBanana ERP - V2
-- Alinha o schema criado pelo Flyway com as entidades JPA atuais.
-- Corrige divergências que antes eram mascaradas por ddl-auto=create-drop.

-- 1) venda_itens: entidade possui data_hora
ALTER TABLE venda_itens
    ADD COLUMN IF NOT EXISTS data_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- 2) pagamentos: entidade usa BIGINT identity + cliente_id (não tenant_id/UUID)
DROP TABLE IF EXISTS pagamentos;

CREATE TABLE pagamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id UUID NOT NULL,
    valor NUMERIC(10,2) NOT NULL,
    data DATE NOT NULL,
    metodo VARCHAR(50) NOT NULL,
    referencia VARCHAR(255),
    confirmado BOOLEAN NOT NULL DEFAULT false,
    CONSTRAINT fk_pagamento_cliente FOREIGN KEY (cliente_id) REFERENCES tenants(id)
);

CREATE INDEX IF NOT EXISTS idx_pagamento_cliente ON pagamentos(cliente_id);
CREATE INDEX IF NOT EXISTS idx_pagamento_data ON pagamentos(data);

-- 3) auditoria_logs: entidade possui usuario_id
ALTER TABLE auditoria_logs
    ADD COLUMN IF NOT EXISTS usuario_id UUID;

CREATE INDEX IF NOT EXISTS idx_auditoria_usuario ON auditoria_logs(usuario_id);
CREATE INDEX IF NOT EXISTS idx_auditoria_data ON auditoria_logs(data_hora);

-- 4) Índices auxiliares que faltavam
CREATE INDEX IF NOT EXISTS idx_venda_vendedor ON vendas(vendedor_id);
CREATE INDEX IF NOT EXISTS idx_venda_status ON vendas(status);
CREATE INDEX IF NOT EXISTS idx_produto_nome ON produtos(nome);
CREATE INDEX IF NOT EXISTS idx_fiado_nome ON fiados(nome_cliente);
